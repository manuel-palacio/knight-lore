// Tiny pixel-art icons rendered as inline SVG. Each is 16×16 and uses the
// item's accent colour. The HUD swaps these in to the carry / wants /
// delivered slots instead of unicode glyphs (which rendered as plain text
// at different sizes per system font).

const W = 16

function pixels(cells: string[], fg: string): string {
  // Each row is a string of N cells; '#' = lit pixel, '.' = empty.
  // Produces a 16×16 SVG with each lit pixel rendered as a <rect>.
  const rects: string[] = []
  const px = W / cells[0]!.length
  for (let y = 0; y < cells.length; y++) {
    const row = cells[y]!
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') {
        rects.push(`<rect x="${x * px}" y="${y * px}" width="${px}" height="${px}" />`)
      }
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${W}" viewBox="0 0 ${W} ${W}" fill="${fg}" shape-rendering="crispEdges">${rects.join('')}</svg>`
}

