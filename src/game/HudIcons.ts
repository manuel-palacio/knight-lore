type IconId = keyof typeof ART

const COLORS: Record<IconId, string> = {
  goblet: '#ffd95a',
  gem: '#66ff88',
  'wine-bottle': '#ff7799',
  'crystal-ball': '#aaddff',
  hero: '#d6c298',
  sun: '#ffd95a',
  moon: '#cce4ff',
}

const cache = new Map<string, string>()

export function iconUrl(id: IconId): string {
  if (cache.has(id)) return cache.get(id)!
  const svg = pixels(ART[id] as unknown as string[], COLORS[id])
  const url = `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`
  cache.set(id, url)
  return url
}

export function isIconId(id: string): id is IconId {
  return id in ART
}
